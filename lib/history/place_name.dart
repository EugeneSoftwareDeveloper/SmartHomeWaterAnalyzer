/// Приводит имя места к каноничному виду: пустое и «пробельное» становятся `null`.
///
/// Нужно, потому что до версии 1.2.0 место было свободным вводом, и в
/// `SharedPreferences` могла остаться строка из одних пробелов. Без нормализации
/// поле показывало бы пустоту, в списке не был бы отмечен ни один пункт, а замер
/// сохранялся бы с «пробельным» местом, которое UI считает названным.
///
/// Живёт в `history/`, а не в виджете выбора места, потому что одним и тем же
/// правилом пользуются трое: поле выбора, запись замера в БД и поиск предыдущего
/// замера для тренда. Разойдись они — тренд искал бы базу по «` Кулер `», а
/// сохранено было бы «`Кулер`», и сравнение молча не находило бы ничего.
String? normalizePlaceName(String? name) {
  final trimmed = name?.trim();
  return (trimmed == null || trimmed.isEmpty) ? null : trimmed;
}
