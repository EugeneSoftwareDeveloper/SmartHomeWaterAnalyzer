import 'package:flutter/widgets.dart';

/// Название языка на нём самом: «Русский», «English».
///
/// Эти подписи сознательно не локализуются. Список языков — единственное место
/// интерфейса, куда приходит человек, случайно включивший язык, которого не
/// знает; переведи подписи — и дорогу назад он будет искать наугад.
String languageName(Locale locale) {
  return switch (locale.languageCode) {
    'ru' => 'Русский',
    'en' => 'English',
    // Язык добавили в supportedLocales, а сюда вписать забыли. Код языка
    // некрасив, но выбрать по нему всё-таки можно — в отличие от пустой строки.
    _ => locale.languageCode.toUpperCase(),
  };
}
